const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  library: dir => ipcRenderer.invoke('library', dir),
  pick: kind => ipcRenderer.invoke('pick', kind),
  exists: email => ipcRenderer.invoke('auth:exists', email),
  register: data => ipcRenderer.invoke('auth:register', data),
  login: data => ipcRenderer.invoke('auth:login', data),
  logout: () => ipcRenderer.invoke('auth:logout'),
  verify: data => ipcRenderer.invoke('auth:verify', data),
  resend: email => ipcRenderer.invoke('auth:resend', email),
  me: () => ipcRenderer.invoke('auth:me'),
  ban: () => ipcRenderer.invoke('auth:ban'),
  onBan: cb => ipcRenderer.on('ban', (_e, b) => cb(b)),
  win: action => ipcRenderer.send('win', action),
  netChecks: () => ipcRenderer.invoke('net:checks'),
  copyReport: text => ipcRenderer.invoke('net:copy', text),
  saveReport: text => ipcRenderer.invoke('net:save', text),
  onMaximized: cb => ipcRenderer.on('maximized', (_e, max) => cb(max)),
  settings: () => ipcRenderer.invoke('set:get'),
  setSettings: patch => ipcRenderer.invoke('set:put', patch),
  onSettings: cb => ipcRenderer.on('settings', (_e, s) => cb(s)),
  info: () => ipcRenderer.invoke('app:info'),
  openLink: name => ipcRenderer.invoke('open:link', name),
  checkUpdate: () => ipcRenderer.invoke('app:update'),
  download: url => ipcRenderer.invoke('app:download', url),
  onUpdateProgress: cb => ipcRenderer.on('update:progress', (_e, p) => cb(p)),
  installUpdate: url => ipcRenderer.invoke('app:install', url),
  pickWall: () => ipcRenderer.invoke('wall:pick'),
  pickAvatar: () => ipcRenderer.invoke('avatar:pick'),
  clearAvatar: () => ipcRenderer.invoke('avatar:clear'),
  setColor: c => ipcRenderer.invoke('profile:color', c),
  search: (q, kind, index) => ipcRenderer.invoke('search', q, kind, index),
  dz: (type, id) => ipcRenderer.invoke('dz:get', type, id),
  full: t => ipcRenderer.invoke('yt:full', t),
  spStatus: () => ipcRenderer.invoke('sp:status'),
  spLogin: () => ipcRenderer.invoke('sp:login'),
  spLogout: () => ipcRenderer.invoke('sp:logout'),
  spToken: () => ipcRenderer.invoke('sp:token'),
  spMatch: t => ipcRenderer.invoke('sp:match', t),
  spPlay: (uri, device, ms) => ipcRenderer.invoke('sp:play', uri, device, ms),
  dzLink: url => ipcRenderer.invoke('dz:link', url),
  linkImport: url => ipcRenderer.invoke('link:import', url),
  dzChart: () => ipcRenderer.invoke('dz:chart'),
  lib: () => ipcRenderer.invoke('lib:get'),
  libDo: (op, a, b) => ipcRenderer.invoke('lib:do', op, a, b),
  onLib: cb => ipcRenderer.on('lib', (_e, l) => cb(l)),
  dropWall: file => ipcRenderer.invoke('wall:set', webUtils.getPathForFile(file)),
  cacheInfo: () => ipcRenderer.invoke('cache:info'),
  clearCache: cats => ipcRenderer.invoke('cache:clear', cats),
  openCache: () => ipcRenderer.invoke('cache:open'),
  lyricsGet: id => ipcRenderer.invoke('lyr:get', id),
  lyricsPut: (id, lines) => ipcRenderer.invoke('lyr:put', id, lines),
  testShortcut: acc => ipcRenderer.invoke('overlay:test', acc),
  showOverlay: on => ipcRenderer.send('overlay:show', on),
  now: info => ipcRenderer.send('now', info),
  onNow: cb => ipcRenderer.on('now', (_e, n) => cb(n)),
  onShown: cb => ipcRenderer.on('overlay:shown', (_e, on) => cb(on)),
  ctl: act => ipcRenderer.send('ctl', act),
  onCtl: cb => ipcRenderer.on('ctl', (_e, a) => cb(a)),
});
